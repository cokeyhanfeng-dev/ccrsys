-- 说明:
--   LPR 参数(ccr_lpr_version):一年期 3.0%/五年期以上 3.5%,由计划财务部人工维护(D12)
--   链式语义:按优先级从低到高,首个满足 申请利率≥岗位边界 的节点终审,小组(SIX_PEOPLE_GROUP)兜底
--   金额三档化(需求三,2026-08-14):对公按申请金额分三档
--     LT_1000(<1000万)/GE_1000_LT_5000(1000万含-5000万)/GE_5000(≥5000万),定档基准改按申请金额;
--     <1000万 档利率区间与个人贷款一致:存量→零售金融部(org_code 3202233991,GM=orig-20BP floor3.8)、
--     新增→授信评审部(org_code 3202233943,BM/GM=LPR+100BP、VP=LPR+80BP、GROUP<LPR+80BP)
--   路由口径(用户拍板):所有贷款申请必经支行行长首节点;支行行长仅在"权限内"单元格
--     (非国企新增1000万-5000万、个人新增、<1000万新增)有终审权,终审边界=该单元格部门总经理线(挂牌价口径),
--     突破边界逐级上送 部门总经理→分管行领导→小组;其余单元格支行行长仅过手不终审(不配 BM 行)
--   存量降幅(SPREAD):边界 = 原利率 - boundary_bp*0.01%,且不低于 boundary_min_rate(绝对下限)
--   存款/保证金(D16b+B13):不设部门层级,支行行长过手;方向 HIGHER_BETTER,
--     boundary_min_rate 为上限语义——申请利率高于上限才需小组表决,否则支行行长权限内终审
--   期限档分轨:贷款 1Y/3Y/5Y(一/三年期用 1Y LPR,五年期用 5Y+ LPR);
--     存款 3M/6M/1Y/2Y/3Y;通知存款按日 1D/7D(产品码 NOTICE_DEPOSIT 区分)
--   部门归属(D16a):对公存量→公司金融部(3202233912);对公新增→授信评审部(3202233943);个人经营贷→零售金融部(3202233991);
--     2026-08-14 机构表 dept_code 列删除,部门归属统一使用机构 org_code
-- ============================================================

USE `ccr_rate`;

-- ---------- 权限矩阵配置表 ----------
CREATE TABLE IF NOT EXISTS `ccr_rate_matrix` (
  `id`                   BIGINT       NOT NULL,
  `tenant_id`            VARCHAR(20)  NOT NULL DEFAULT '000000',
  `business_no`          VARCHAR(64)  NOT NULL,
  `org_id`               BIGINT       NOT NULL,
  `status`               VARCHAR(32)  NOT NULL DEFAULT 'EFFECTIVE' COMMENT 'DRAFT/REVIEW/EFFECTIVE/INVALID',
  `version_no`           INT          NOT NULL DEFAULT 1,
  `create_dept`          BIGINT       NULL,
  `create_by`            BIGINT       NOT NULL,
  `create_time`          DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `update_by`            BIGINT       NULL,
  `update_time`          DATETIME     NULL,
  `del_flag`             CHAR(1)      NOT NULL DEFAULT '0',
  `matrix_no`            VARCHAR(64)  NOT NULL COMMENT '矩阵行编码(唯一)',
  `business_big_type`    VARCHAR(32)  NOT NULL COMMENT '业务大类:LOAN_PUBLIC对公贷款/LOAN_PERSONAL个人贷款/DEPOSIT存款/MARGIN保证金',
  `new_or_existing`      VARCHAR(16)  NOT NULL COMMENT 'NEW新增授信/EXISTING存量授信',
  `customer_type`        VARCHAR(16)  NULL COMMENT 'SOE国企/NON_SOE非国企/PERSONAL个人(空=通配)',
  `product_code`         VARCHAR(32)  NULL COMMENT '产品编码(空=通配;存款/保证金区分:AGREEMENT_DEPOSIT协定/NOTICE_DEPOSIT通知/BILL_MARGIN银票/CREDIT_MARGIN信用证)',
  `amount_tier`          VARCHAR(16)  NULL COMMENT '金额档:LT_1000(<1000万)/GE_1000_LT_5000(1000万含-5000万)/GE_5000(≥5000万),空=通配;定档基准按申请金额(需求三,2026-08-14)',
  `term_tier`            VARCHAR(16)  NULL COMMENT '期限档:贷款1Y/3Y/5Y;存款3M/6M/1Y/2Y/3Y;通知存款1D/7D,空=通配',
  `guarantee_type`       VARCHAR(32)  NULL COMMENT '担保主类型(空=通配;逐担保类型路由 D18a)',
  `start_node_code`      VARCHAR(64)  NOT NULL COMMENT '终审岗位:BRANCH_MANAGER/DEPT_GENERAL_MANAGER/VICE_PRESIDENT/SIX_PEOPLE_GROUP',
  `dept_code`            VARCHAR(64)  NULL COMMENT '部门归属(D16a):机构org_code——3202233912公司金融部/3202233943授信评审部/3202233991零售金融部(2026-08-14 统一 org_code)',
  `boundary_type`        VARCHAR(16)  NOT NULL COMMENT '边界语义:RATE直接利率 / SPREAD降幅(存量)',
  `boundary_min_rate`    DECIMAL(9,6) NULL COMMENT '绝对值利率(%);贷款新增=该岗位最低可批;存量=绝对下限;存款/保证金=期限上限(高于才上会)',
  `boundary_bp`          INT          NULL COMMENT 'BP:新增授信=LPR±BP;存量=最大可降BP(降幅阈值)',
  `bp_sign`              VARCHAR(1)   NULL COMMENT '+/-:BP方向(新增授信相对LPR)',
  `lpr_term`             VARCHAR(8)   NULL COMMENT 'BP对应的LPR期限(1Y/5Y+),决定用哪个LPR换算',
  `priority`             INT          NOT NULL DEFAULT 0 COMMENT '匹配优先级(低值优先;链式:1支行/2部门总经理/3分管行领导/4小组)',
  `effective_from`       DATETIME     NOT NULL COMMENT '生效时间',
  `effective_to`         DATETIME     NULL COMMENT '失效时间',
  `publish_by`           BIGINT       NULL COMMENT '发布人(双人复核)',
  `review_by`            BIGINT       NULL COMMENT '复核人',
  `publish_time`         DATETIME     NULL COMMENT '发布时间',
  `remark`               VARCHAR(500) NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_matrix_no` (`matrix_no`),
  KEY `idx_matrix_dim` (`business_big_type`,`new_or_existing`,`customer_type`,`amount_tier`,`term_tier`)
) ENGINE=InnoDB COMMENT='PRD V2 §7.2 权限矩阵(LPR±BP路由)';

