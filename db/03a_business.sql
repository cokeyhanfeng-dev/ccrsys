  `term_unit`           VARCHAR(8)   NOT NULL COMMENT '日/月/年',
  `pricing_amount`      DECIMAL(20,4) NOT NULL COMMENT '分项定价金额(万元)',
  `currency`            VARCHAR(8)   NOT NULL DEFAULT 'CNY' COMMENT '币种',
