  `del_flag`            CHAR(1)      NOT NULL DEFAULT '0' COMMENT '逻辑删除标识',
  `application_no`      VARCHAR(64)  NOT NULL COMMENT '申请号(唯一)',
  `business_type`       VARCHAR(16)  NOT NULL COMMENT 'LOAN贷款/DEPOSIT存款',
  `customer_scope`      VARCHAR(16)  NOT NULL COMMENT 'INDIVIDUAL/CORPORATE_SINGLE/GROUP',
  `customer_no`         VARCHAR(64)  NULL COMMENT '个人或企业单户客户号(集团场景为空)',
  `group_no`            VARCHAR(64)  NULL COMMENT '集团客户编号(集团场景必填)',
  `applicant_user_id`   BIGINT       NOT NULL COMMENT '客户经理',
  `applicant_org_id`    BIGINT       NOT NULL COMMENT '提交机构',
  `source_application_id` BIGINT     NULL COMMENT '关联重提的原申请',
  `snapshot_bundle_id`  BIGINT       NULL COMMENT '提交成功绑定不可变快照包',
  `rule_set_version_id` BIGINT       NULL COMMENT '冻结利率规则集版本',
  `lpr_version_id`      BIGINT       NULL COMMENT '冻结LPR版本',
  `flow_definition_version` VARCHAR(64) NULL COMMENT '冻结流程定义版本',
  `submit_time`         DATETIME     NULL COMMENT '最终提交时间',
  `final_time`          DATETIME     NULL COMMENT '主申请终态时间',
  `application_remark`  VARCHAR(1000) NULL COMMENT '客户经理备注(手工描述,展示在审批界面)',
  `route_as_of_date`    DATETIME     NULL COMMENT '提交冻结的路由/LPR生效日期(§8.4,在途沿用)',
  `data_baseline_json`  JSON         NULL COMMENT '草稿创建/上次预览时各数仓数据集数据日期基线(§7.1步骤9比对)',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_application_no` (`application_no`),
  KEY `idx_app_org_status` (`applicant_org_id`,`status`),
  KEY `idx_app_applicant` (`applicant_user_id`,`status`),
  KEY `idx_app_create` (`create_time`),
  KEY `idx_app_customer` (`customer_no`),
  KEY `idx_app_group` (`group_no`)
) ENGINE=InnoDB COMMENT='ccr_application 利率申请主单';

