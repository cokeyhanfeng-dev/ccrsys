  `requested_rate`      DECIMAL(9,6) NOT NULL COMMENT '客户经理申请利率',
  `current_approval_rate` DECIMAL(9,6) NOT NULL COMMENT '当前审批利率(随调价更新)',
  `final_rate`          DECIMAL(9,6) NULL COMMENT '最终决议利率',
  `rate_direction`      VARCHAR(16)  NOT NULL COMMENT 'LOWER_BETTER/HIGHER_BETTER',
  `route_code`          VARCHAR(64)  NULL COMMENT '计算得到路由编码',
  `flow_instance_id`    VARCHAR(64)  NULL COMMENT '工作流实例标识',
  `current_node_code`   VARCHAR(64)  NULL COMMENT '当前节点编码',
  `start_node_code`     VARCHAR(64)  NULL COMMENT '审批链首节点编码(提交路由后冻结,§8.6;贷款/存款恒为BRANCH_MANAGER)',
