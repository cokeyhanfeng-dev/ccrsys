  `matched_matrix_no`   VARCHAR(64)  NULL COMMENT '命中的权限矩阵行编号(提交路由后冻结,审计溯源,§8.6)',
  `final_reason`        VARCHAR(1000) NULL COMMENT '最终否决或一票否决原因',
  `source_pricing_item_id` BIGINT    NULL COMMENT '关联重提来源分项(§7.6)',
  `inherit_flag`        CHAR(1)      NOT NULL DEFAULT 'N' COMMENT '是否沿用原决议Y/N(D18b:已批准分项连同最终利率与快照保留,不重新审批)',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_pricing_item_no` (`pricing_item_no`),
  KEY `idx_pricing_app_status` (`application_id`,`status`),
  KEY `idx_pricing_node_status` (`current_node_code`,`status`),
  KEY `idx_pricing_customer` (`pricing_customer_no`,`create_time`),
  KEY `idx_pricing_member` (`member_customer_no`),
  KEY `idx_pricing_source` (`source_pricing_item_id`)
) ENGINE=InnoDB COMMENT='ccr_pricing_item 利率定价分项(审批原子单位)';

